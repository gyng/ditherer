import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const packageRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const filtersRoot = path.join(packageRoot, "src/filters");
const generatedRoot = path.join(packageRoot, "src/generated");
const checkOnly = process.argv.includes("--check");

const server = await createServer({
  root: packageRoot,
  configFile: false,
  appType: "custom",
  logLevel: "silent",
  server: { middlewareMode: true, hmr: false },
});

let registry;
const originalWarn = console.warn;
const originalError = console.error;
console.warn = () => {};
console.error = () => {};
try {
  registry = await server.ssrLoadModule("/src/filters/index.ts");
} finally {
  console.warn = originalWarn;
  console.error = originalError;
}

const filterFiles = (await readdir(filtersRoot))
  .filter((name) => name.endsWith(".ts") && !name.endsWith(".d.ts") && name !== "index.ts")
  .sort();
const canonicalNames = new Set(Object.keys(registry.filterIndex));
const candidates = new Map();

try {
  for (const file of filterFiles) {
    const moduleName = file.slice(0, -3);
    const loaded = await server.ssrLoadModule(`/src/filters/${file}`);
    for (const [exportName, value] of Object.entries(loaded)) {
      if (
        !value
        || typeof value !== "object"
        || typeof value.name !== "string"
        || typeof value.func !== "function"
        || !canonicalNames.has(value.name)
      ) continue;
      const current = candidates.get(value.name);
      if (!current || exportName === "default") {
        candidates.set(value.name, { moduleName, exportName });
      }
    }
  }
} finally {
  await server.close();
}

const missing = [...canonicalNames].filter((name) => !candidates.has(name));
if (missing.length > 0) {
  throw new Error(`No selective module export found for: ${missing.join(", ")}`);
}

const loaderRows = [...canonicalNames].sort().map((name) => {
  const { moduleName, exportName } = candidates.get(name);
  const access = exportName === "default" ? "module.default" : `module[${JSON.stringify(exportName)}]`;
  return `  ${JSON.stringify(name)}: () => import("../filters/${moduleName}").then((module) => ${access} as FilterDefinition),`;
});
const loadersSource = `// Generated by scripts/generate-selective-entries.mjs. Do not edit.\n`
  + `import type { FilterDefinition } from "../filters/types";\n\n`
  + `export const filterLoaders = {\n${loaderRows.join("\n")}\n} satisfies Record<string, () => Promise<FilterDefinition>>;\n`;

const catalog = registry.filterList.map((entry) => ({
  displayName: entry.displayName,
  filterName: entry.filter.name,
  category: entry.category,
  description: entry.description,
}));
const catalogSource = `// Generated by scripts/generate-selective-entries.mjs. Do not edit.\n`
  + `import type { FilterCatalogEntry } from "../catalog";\n\n`
  + `export const filterCatalog = ${JSON.stringify(catalog, null, 2)} as const satisfies readonly FilterCatalogEntry[];\n`;

const modules = [...new Set([...candidates.values()].map(({ moduleName }) => moduleName))].sort();
const manifestSource = `${JSON.stringify(modules, null, 2)}\n`;
const outputs = new Map([
  [path.join(generatedRoot, "filter-loaders.ts"), loadersSource],
  [path.join(generatedRoot, "filter-catalog.ts"), catalogSource],
  [path.join(generatedRoot, "filter-modules.json"), manifestSource],
]);

await mkdir(generatedRoot, { recursive: true });
for (const [filename, contents] of outputs) {
  if (checkOnly) {
    const existing = await readFile(filename, "utf8").catch(() => "");
    if (existing !== contents) {
      throw new Error(`${path.relative(packageRoot, filename)} is stale; run npm run generate`);
    }
  } else {
    await writeFile(filename, contents);
  }
}

console.log(
  `${checkOnly ? "Verified" : "Generated"} ${canonicalNames.size} lazy filters, `
  + `${modules.length} public modules, and ${catalog.length} catalog rows`,
);
